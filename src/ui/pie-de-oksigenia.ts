/** El icono de una red, que es decorado: el nombre lo lleva el enlace. */
export function iconoDeRed(red: Red): string {
  return `<svg aria-hidden="true" focusable="false" viewBox="${red.viewBox}" xmlns="http://www.w3.org/2000/svg"><path d="${red.d}"/></svg>`;
}

/**
 * El pie, para los créditos.
 *
 * **Todo lo de fuera, en otra pestaña.** Un enlace que se abriera en la misma
 * se llevaría el juego por delante, con el vuelo a medias. El correo no: abre
 * el programa de correo y el juego se queda donde estaba.
 *
 * Y `rel="me"` en las redes, como en todas las webs de Oksigenia: es lo que
 * dice que esas cuentas son las de quien firma la página.
 */
export function pieDeOksigenia(): string {
  const fuera = 'target="_blank" rel="noopener noreferrer"';
  return `
    <footer class="creditos__pie">
      <p class="creditos__firma">
        <a href="${OKSIGENIA}" ${fuera}>${t("credits.firma")}</a>
        <a href="mailto:${CORREO}">${CORREO}</a>
        <a href="${SELLO}" ${fuera}>${t("credits.sello")}</a>
      </p>
      <ul class="creditos__redes" aria-label="${t("credits.redes")}">${REDES.map(
        (red) =>
          `<li><a href="${red.url}" target="_blank" rel="me noopener noreferrer" aria-label="${t(
            "credits.red",
            { red: red.nombre },
          )}">${iconoDeRed(red)}</a></li>`,
      ).join("")}</ul>
    </footer>
  `;
}
